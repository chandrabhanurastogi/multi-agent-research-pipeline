"""Briefing output, audit file and CLI, using the fake agents from tests/fakes.py."""

from datetime import date

import pytest
from fakes import QUERY, agents, provider_down

from research_pipeline import app
from research_pipeline.memory.audit import load_run, save_run
from research_pipeline.reporting.briefing_writer import build_briefing, render_markdown
from research_pipeline.tools.search import Corpus
from research_pipeline.workflows.research_briefing import run

AS_OF = date(2026, 10, 1)
SECTIONS = ["## How we read your question", "## Summary", "## Overall assessment", "## Key findings",
            "## Where sources disagree", "## What we could not establish", "## Statements we could not verify",
            "## Suggested follow-up questions", "## Sources", "## About this briefing"]


@pytest.fixture(scope="module")
def corpus():
    return Corpus.load()


def markdown_for(state) -> str:
    return render_markdown(build_briefing(state))


def test_every_section_appears_in_fixed_order(corpus):
    md = markdown_for(run(QUERY, agents(), corpus, as_of=AS_OF))
    positions = [md.index(s) for s in SECTIONS]
    assert positions == sorted(positions)


def test_findings_show_support_label_explanation_and_sources(corpus):
    briefing = build_briefing(run(QUERY, agents(), corpus, as_of=AS_OF))
    first = briefing.key_findings[0]
    assert first.sources and first.explanation.startswith("Best source:")
    md = render_markdown(briefing)
    assert "supported by our sources" in md and "not a probability" in md


def test_no_evidence_run_explains_itself(corpus):
    md = markdown_for(run(QUERY, agents(researcher=provider_down), corpus, as_of=AS_OF))
    assert "Needs human review" in md
    assert "We could not find credible sources" in md
    assert "Find sources that answer:" in md  # follow-ups generated by code from the gaps


def test_unverified_run_carries_a_banner(corpus):
    md = markdown_for(run(QUERY, agents(verifier=provider_down), corpus, as_of=AS_OF))
    assert "NOT VERIFIED" in md and "Needs human review" in md


def test_saved_run_loads_back(corpus, tmp_path):
    state = run(QUERY, agents(), corpus, as_of=AS_OF)
    assert load_run(save_run(state, tmp_path)) == state


def test_cli_writes_briefing_and_audit_files(monkeypatch, tmp_path, capsys):
    # Replace the real model with the fake agents: the CLI runs fully offline.
    monkeypatch.setattr(app, "configured_model", lambda: "fake")
    monkeypatch.setattr(app, "model_name", lambda: "fake")
    monkeypatch.setattr(app, "fallback_model_names", lambda: [])
    monkeypatch.setattr(app, "build_agents", lambda model: agents())

    assert app.main([QUERY, "--runs-dir", str(tmp_path)]) == 0
    [run_folder] = tmp_path.iterdir()
    assert {p.name for p in run_folder.iterdir()} == {"briefing.md", "run.json"}
    assert "Briefing:" in capsys.readouterr().out


@pytest.mark.parametrize("query", ["hi", "   ", "x" * 1001])
def test_cli_rejects_bad_query_before_any_work(monkeypatch, tmp_path, capsys, query):
    called = []
    monkeypatch.setattr(app, "configured_model", lambda: called.append("model"))
    assert app.main([query, "--runs-dir", str(tmp_path)]) == 2
    assert "Please ask a question" in capsys.readouterr().err
    assert called == [] and list(tmp_path.iterdir()) == []  # no model built, nothing written
